#!/usr/bin/env node
// Build lib/p6/dex838-parse.mjs from the DEX838 parser in dexspine-core at a pinned commit.
// The parser is copied unchanged between two marker lines; the header records the commit and the sha256 of the copy.
// Usage: node tools/make-dex838.mjs --from <dexspine-core clone> --commit <sha>        (writes the module)
//        node tools/make-dex838.mjs --from <dexspine-core clone> --check                (checks the module against its pinned commit)
// Run it when the pin moves, then npm run build. npm run build itself never needs a dexspine-core clone.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const MODULE = path.join(ROOT, 'lib', 'p6', 'dex838-parse.mjs');
export const BEGIN = '// ---- begin dexspine-core src/dex838.js ----';
export const END = '// ---- end dexspine-core src/dex838.js ----';

export const sha256 = (text) => crypto.createHash('sha256').update(text, 'utf8').digest('hex');

/** The parser source at a commit of a dexspine-core clone, with LF line ends. */
export function sourceAt(clone, commit) {
  return execFileSync('git', ['-C', clone, 'show', `${commit}:src/dex838.js`], { encoding: 'utf8' }).replace(/\r\n/g, '\n');
}

/** The pinned commit, the recorded hash and the embedded copy, read back from the module. */
export function readModule(text = fs.readFileSync(MODULE, 'utf8')) {
  const t = text.replace(/\r\n/g, '\n');
  const m = /^\/\/ source: dexspine-core ([0-9a-f]{7,40}) src\/dex838\.js sha256:([0-9a-f]{64})$/m.exec(t);
  const a = t.indexOf(BEGIN + '\n');
  const b = t.indexOf('\n' + END);
  if (!m || a < 0 || b < 0) return null;
  return { commit: m[1], hash: m[2], copy: t.slice(a + BEGIN.length + 1, b + 1) };
}

const RUN = `
/** Parse one DEX838 line. Strict by default: a line that does not parse is reported, never acted on. */
export function run(input) {
  if (!input || typeof input !== 'object' || typeof input.line !== 'string') return { ok: false, error: 'input.line must be a string' };
  const strict = input.strict !== false;
  try {
    const parsed = parseDEX838(input.line, { strict });
    return { ok: true, parsed, trace: { node: 'L4.E02', strict } };
  } catch (e) {
    return { ok: false, error: String(e && e.message ? e.message : e).slice(0, 300), trace: { node: 'L4.E02', strict } };
  }
}
`;

function build(clone, commit) {
  const full = execFileSync('git', ['-C', clone, 'rev-parse', commit], { encoding: 'utf8' }).trim();
  const src = sourceAt(clone, full);
  if (/^\s*import\s/m.test(src)) throw new Error('the parser imports something; the engine bundle inlines dependency-free modules only');
  const text = [
    '// node: L4.E02',
    '// input: { line: string, strict?: boolean }',
    `// source: dexspine-core ${full} src/dex838.js sha256:${sha256(src)}`,
    '// Generated by tools/make-dex838.mjs from the pinned dexspine-core commit. Never edit by hand: change dexspine-core, then rebuild.',
    BEGIN,
    src.trimEnd(),
    END,
    RUN,
  ].join('\n');
  fs.mkdirSync(path.dirname(MODULE), { recursive: true });
  fs.writeFileSync(MODULE, text);
  console.log(`Wrote lib/p6/dex838-parse.mjs from dexspine-core ${full.slice(0, 7)}.`);
}

function check(clone) {
  const m = readModule();
  if (!m) { console.log('lib/p6/dex838-parse.mjs has no source header or markers.'); process.exit(1); }
  const problems = [];
  if (sha256(m.copy) !== m.hash) problems.push('the copy in the module does not match the hash in its header');
  if (clone && sha256(sourceAt(clone, m.commit)) !== m.hash) problems.push(`the copy does not match dexspine-core ${m.commit.slice(0, 7)}`);
  if (problems.length) { for (const p of problems) console.log(p); process.exit(1); }
  console.log(`lib/p6/dex838-parse.mjs matches dexspine-core ${m.commit.slice(0, 7)}${clone ? '' : ' (header only; pass --from to check the source too)'}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
  const clone = opt('--from');
  if (args.includes('--check')) check(clone);
  else if (clone && opt('--commit')) build(clone, opt('--commit'));
  else { console.log('Usage: node tools/make-dex838.mjs --from <dexspine-core clone> --commit <sha> | --check [--from <clone>]'); process.exit(2); }
}
